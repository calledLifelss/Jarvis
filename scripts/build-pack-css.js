// Build renderer/pack-icons.css from renderer/icons/<pack>/*.svg.
// Each pack block sets --pack-icon-<slot> to a data-uri mask. Masks get
// black paint (mask uses alpha). Run: node scripts/build-pack-css.js
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..', 'renderer', 'icons');
const OUT = path.join(__dirname, '..', 'renderer', 'pack-icons.css');
const SLOTS = ['backend', 'sessions', 'cron', 'sound', 'dock', 'settings', 'clip', 'mic', 'send'];

function maskUri(svg) {
  const black = svg.split('currentColor').join('black');
  return 'url("data:image/svg+xml,' + encodeURIComponent(black)
    .replace(/'/g, '%27').replace(/"/g, '%27') + '")';
}

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
const packs = Object.keys(manifest.packs).sort();

let css = `/* Pack icon masks — GENERATED by scripts/build-pack-css.js, do not edit.
   One block per theme pack: --pack-icon-<slot> data-uri masks built from
   renderer/icons/<pack>/*.svg (fetched from Iconify, see manifest.json).
   The swap rules below hide the inline house SVG inside each themed pack so
   the mask cuts the pack glyph out of a solid currentColor block; the house
   theme (jarvis-dark, no vars) keeps its real Lucide strokes. */\n`;

const SWAP = `#rail-backend .ic, #rail-sessions .ic, #rail-cron .ic,
#btn-sound .ic, #btn-dock .ic, #btn-settings .ic,
#btn-clip svg, #btn-mic svg, #btn-send svg`;
const SWAP_INNER = `#rail-backend .ic > *, #rail-sessions .ic > *, #rail-cron .ic > *,
#btn-sound .ic > *, #btn-dock .ic > *, #btn-settings .ic > *,
#btn-clip svg > *, #btn-mic svg > *, #btn-send svg > *`;

for (const pack of packs) {
  css += `\n/* ${pack} — ${manifest.packs[pack].set} */\n[data-theme="${pack}"] {\n`;
  for (const slot of SLOTS) {
    const f = path.join(ROOT, pack, `${slot}.svg`);
    if (!fs.existsSync(f)) { console.error(`MISSING ${pack}/${slot}`); continue; }
    const svg = fs.readFileSync(f, 'utf8').trim();
    css += `  --pack-icon-${slot}: ${maskUri(svg)};\n`;
  }
  css += '}\n';
  // swap: inside this pack, inline house strokes hide and the svg becomes a
  // solid block the mask cuts into the pack glyph
  css += `[data-theme="${pack}"] ${SWAP.split('\n').join(',\n' + `[data-theme="${pack}"] `)} {\n  color: transparent;\n  background: currentColor;\n}\n`;
  css += `[data-theme="${pack}"] ${SWAP_INNER.split('\n').join(',\n' + `[data-theme="${pack}"] `)} {\n  display: none;\n}\n`;
}
fs.writeFileSync(OUT, css);
console.log(`wrote pack-icons.css (${packs.length} packs, ${(fs.statSync(OUT).size / 1024).toFixed(0)}KB)`);
